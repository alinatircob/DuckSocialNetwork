package org.example.ducksocialnetworkm.domeniu.user;

/**
 * Interfață care definește comportamentul de zbor al unei rațe.
 * Clasele care implementează această interfață trebuie să definească metoda {@code zboara()}.
 */
public interface Zburator {

    /**
     * Metodă care descrie acțiunea de zbor.
     */
    void zboara();
}