package org.example.ducksocialnetworkm.domeniu.user;

/**
 * Interfață care definește comportamentul unui înotător.
 * Orice clasă care implementează această interfață trebuie să definească metoda {@code inoata()}.
 */
public interface Inotator {

    /**
     * Metodă care descrie acțiunea de înot.
     */
    void inoata();
}
